create table if not exists public.test_results (
  id bigint generated by default as identity primary key,
  participant_name text not null check (char_length(trim(participant_name)) between 1 and 40),
  correct_answers integer not null check (correct_answers between 0 and 10),
  total_questions integer not null default 10 check (total_questions = 10),
  percentage integer not null check (percentage between 0 and 100),
  result_category text not null check (result_category in (
    'Цифровой эксперт', 'Уверенный пользователь',
    'Цифровой исследователь', 'Новичок цифрового мира'
  )),
  created_at timestamptz not null default now(),
  constraint test_results_percentage_matches_score
    check (percentage = round(correct_answers * 100.0 / total_questions))
);
alter table public.test_results enable row level security;
create policy "Anyone can insert test results"
on public.test_results for insert to anon
with check (
  char_length(trim(participant_name)) between 1 and 40
  and correct_answers between 0 and 10
  and total_questions = 10 and percentage between 0 and 100
);
create policy "Anyone can read leaderboard"
on public.test_results for select to anon using (true);
